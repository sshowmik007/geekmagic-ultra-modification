import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

export function buildEspAssets() {
  const distDir = path.join(rootDir, "dist");
  const littlefsDir = path.join(distDir, "littlefs");

  if (!fs.existsSync(distDir)) fs.mkdirSync(distDir, { recursive: true });
  if (!fs.existsSync(littlefsDir)) fs.mkdirSync(littlefsDir, { recursive: true });

  const htmlPath = path.join(rootDir, "index.html");
  const cssPath = path.join(distDir, "styles.css");
  const stateJsPath = path.join(rootDir, "src", "state.js");
  const apiJsPath = path.join(rootDir, "src", "api.js");
  const mainJsPath = path.join(rootDir, "src", "main.js");

  let html = fs.readFileSync(htmlPath, "utf8");
  const css = fs.existsSync(cssPath) ? fs.readFileSync(cssPath, "utf8") : "";
  const stateJs = fs.readFileSync(stateJsPath, "utf8");
  const apiJs = fs.readFileSync(apiJsPath, "utf8");
  const mainJs = fs.readFileSync(mainJsPath, "utf8");

  // Inline CSS
  html = html.replace(
    /<link\s+rel="stylesheet"\s+href="[^"]*"\s*\/?>/i,
    `<style>${css}</style>`
  );

  // Combine JS modules into a single bundle
  // Strip import/export statements for seamless single-script execution
  const bundledJs = `
// --- State Module ---
${stateJs.replace(/export\s+/g, "")}

// --- API Module ---
${apiJs.replace(/export\s+/g, "")}

// --- Main Module ---
${mainJs
  .replace(/import\s+[^;]+;\s*/g, "")
  .replace(/export\s+function\s+renderDashboard/g, "function renderDashboard")}
  `.trim();

  // Inline JS
  html = html.replace(
    /<script\s+type="module"\s+src="[^"]*"><\/script>/i,
    `<script>${bundledJs}</script>`
  );

  // Simple minification: collapse multiple newlines and spaces outside tags
  const minifiedHtml = html.replace(/\n\s+/g, "\n").trim();
  const rawBytes = Buffer.from(minifiedHtml, "utf8");

  // Gzip compression level 9
  const gzippedBytes = zlib.gzipSync(rawBytes, { level: 9 });

  // 1. Write LittleFS file
  const littlefsGzPath = path.join(littlefsDir, "index.html.gz");
  fs.writeFileSync(littlefsGzPath, gzippedBytes);

  // 2. Format C byte array for PROGMEM
  let hexBytes = "";
  for (let i = 0; i < gzippedBytes.length; i++) {
    const hex = "0x" + gzippedBytes[i].toString(16).padStart(2, "0");
    hexBytes += hex + ", ";
    if ((i + 1) % 16 === 0) hexBytes += "\n  ";
  }

  const headerContent = `// Auto-generated by build-esp.js
// SmallTV-Ultra Web Dashboard (PROGMEM Gzip Bundle)
#ifndef WEB_ASSETS_H
#define WEB_ASSETS_H

#include <Arduino.h>

const size_t DASHBOARD_HTML_GZ_LEN = ${gzippedBytes.length};
const uint8_t DASHBOARD_HTML_GZ[] PROGMEM = {
  ${hexBytes.trim().replace(/,$/, "")}
};

// C++ Helper to register route on ESP8266WebServer
// Usage in setup():
//   serveDashboard(server);
template <typename ServerType>
void serveDashboard(ServerType &server) {
  server.on("/", HTTP_GET, [&server]() {
    server.sendHeader("Content-Encoding", "gzip");
    server.send_P(200, "text/html", (PGM_P)DASHBOARD_HTML_GZ, DASHBOARD_HTML_GZ_LEN);
  });
}

#endif // WEB_ASSETS_H
`;

  const headerPath = path.join(distDir, "web_assets.h");
  fs.writeFileSync(headerPath, headerContent);

  const rawKb = (rawBytes.length / 1024).toFixed(2);
  const gzKb = (gzippedBytes.length / 1024).toFixed(2);
  const budgetPercent = ((gzippedBytes.length / 1048576) * 100).toFixed(2);

  return {
    rawBytes: rawBytes.length,
    gzippedBytes: gzippedBytes.length,
    rawKb,
    gzKb,
    budgetPercent,
    headerPath,
    littlefsGzPath,
  };
}

if (process.argv[1] && process.argv[1].endsWith("build-esp.js")) {
  console.log("Packaging SmallTV Dashboard for ESP8266...");
  const result = buildEspAssets();
  console.log("\n==========================================");
  console.log("  SmallTV-Ultra ESP8266 Bundle Summary    ");
  console.log("==========================================");
  console.log(`Uncompressed:    ${result.rawBytes} bytes (${result.rawKb} KB)`);
  console.log(`Gzip Compressed: ${result.gzippedBytes} bytes (${result.gzKb} KB)`);
  console.log(`Flash Impact:    ${result.budgetPercent}% of 1MB Flash budget`);
  console.log(`PROGMEM Header:  dist/web_assets.h`);
  console.log(`LittleFS File:   dist/littlefs/index.html.gz`);
  console.log("==========================================\n");
}
